def merge_into_rules_json(surface_rules: List[Dict[str, Any]]) -> Dict[str, Any]:
    path = BASE / "defense" / "rules.json"
    payload = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"rules": []}
    existing = [r for r in payload.get("rules", []) if not str(r.get("rule_id", "")).startswith(PREFIX)]
    rules = existing + surface_rules

    payload["rules"] = rules
    payload["built_at"] = datetime.now(timezone.utc).isoformat()
    payload["counts"] = {
        "total": len(rules),
        "threshold": sum(1 for r in rules if r.get("rule_type") == "threshold"),
        "composite": sum(1 for r in rules if r.get("rule_type") == "composite"),
        "signal": sum(1 for r in rules if r.get("rule_type") == "signal"),
        "surface": sum(1 for r in rules if r.get("rule_type") == "surface"),
    }
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return payload


def main() -> None:
    surface_rules = build_surface_rules()
    payload = merge_into_rules_json(surface_rules)
    by_engine: Dict[str, int] = {}
    controls: set = set()
    for rule in surface_rules:
        for engine in rule["engines"]:
            by_engine[engine] = by_engine.get(engine, 0) + 1
        controls.add(rule["control_id"])
    print(f"surface rules: {len(surface_rules)} across {len(by_engine)} engines")
    for engine, count in sorted(by_engine.items()):
        print(f"  {engine:18s} {count} rules")
    print(f"distinct CTL ids targeted: {len(controls)}")
    print(f"rules.json total: {payload['counts']}")


if __name__ == "__main__":
    main()
