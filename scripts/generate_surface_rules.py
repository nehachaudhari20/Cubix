#!/usr/bin/env python3
"""
Generate the non-payment control-surface rules and merge them into rules.json.

These rules are what give each KB family its own verdict. The sandbox has one
handler per surface; the *control identity* of an attack comes from here plus the
family's `targeted_control_ids`. Each rule below names a specific CTL id drawn
from the families that surface serves, so a prompt-injection attempt trips
CTL-0236/0237 while a memory-poisoning attempt trips CTL-0240 — through the same
handler.

Merge is idempotent: every rule here has a `RUL-SURF-` prefix, and existing
`RUL-SURF-` rules are replaced rather than duplicated. Payment rules generated by
generate_kb_rules.py are left untouched.
"""

from __future__ import annotations

