BASE = ROOT / "data" / "knowledge" / "canonical"

PREFIX = "RUL-SURF-"


def _rule(
    rule_id: str,
    name: str,
    engine: str,
    registry: str,
    conditions: List[Dict[str, Any]],
    risk_param: str,
    trigger: str,
    control_id: str,
    expected: List[str],
    *,
    logic: str = "all",
    signal_ids: List[str] | None = None,
    risk_default: float = 0.25,
    risk_cap: float = 0.85,
) -> Dict[str, Any]:
    return {
        "rule_id": f"{PREFIX}{rule_id}",
        "name": name,
        "rule_type": "surface",
        "engines": [engine],
        "signal_ids": signal_ids or [],
        "logic": logic,
        "conditions": conditions,
        "risk_contribution": {
            "param": risk_param,
            "registry": registry,
            "default": risk_default,
        },
        "trigger": trigger,
        "control_id": control_id,
        "expected_control_ids": expected,
        "risk_cap": risk_cap,
        "enabled": True,
        "origin": "surface_control_mapped",
    }


def _gt(field: str, param: str, registry: str, default: float) -> Dict[str, Any]:
    return {"field": field, "op": ">=", "param": param, "registry": registry, "default": default}


def _lt(field: str, param: str, registry: str, default: float) -> Dict[str, Any]:
    return {"field": field, "op": "<", "param": param, "registry": registry, "default": default}


def _flag(field: str) -> Dict[str, Any]:
    return {"field": field, "op": "truthy"}


